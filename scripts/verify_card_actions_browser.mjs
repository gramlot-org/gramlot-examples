import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {galleryRow} from './gallery-navigation.mjs';

const browser = await chromium.launch({headless:true});
try {
    const page = await browser.newPage({viewport:{width:1440,height:1050}});
    const errors=[]; page.on('pageerror', e=>errors.push(e.message));
    await page.goto(process.argv[2]);
    await page.waitForFunction(()=>window.gramlot?.state==='started');
    await (await galleryRow(page,'g05')).click();
    const frame=await (await page.locator('#frame-g05').elementHandle()).contentFrame();
    await frame.waitForFunction(()=>window.gramlot?.state==='started');
    await frame.locator('#actions-address-city input').waitFor();
    const delivery=frame.locator('#actions-delivery');
    const address=frame.locator('#actions-address');
    const open=async card=>card.getByRole('button',{name:/^Actions for/}).first().click();
    await open(delivery);
    await frame.getByRole('button',{name:'Morning delivery',exact:true}).click();
    assert.match(await frame.locator('#actions-status').textContent(),/Morning delivery requested/);
    await open(delivery);
    await frame.getByRole('button',{name:'Prepare contact note',exact:true}).click();
    assert.match(await frame.locator('#actions-status').textContent(),/Alex Morgan.*7946/);
    await frame.locator('#actions-address-city input').fill('Bath');
    // The nested card clears only the destination, retaining parent fields.
    await open(address);
    await frame.getByRole('button',{name:'Clear',exact:true}).click();
    await frame.getByRole('button',{name:'Confirm',exact:true}).click();
    assert.equal(await frame.locator('#actions-address-city input').inputValue(),'');
    assert.equal(await frame.locator('#actions-contact input').inputValue(),'Alex Morgan');
    assert.equal(await frame.locator('#actions-phone input').inputValue(),'+44 20 7946 0420');
    await frame.locator('#actions-address-city input').fill('Bath');
    await delivery.getByRole('checkbox',{name:'Reviewed',exact:true}).check();
    await address.getByRole('button',{name:'Collapse card',exact:true}).click();
    await open(delivery);
    await frame.getByRole('button',{name:'Clear',exact:true}).click();
    await frame.getByRole('button',{name:'Cancel',exact:true}).click();
    assert.equal(await frame.locator('#actions-city-summary').textContent(),'Bath');
    // Keyboard opens the shared menu and Escape returns focus to the header.
    const opener=delivery.getByRole('button',{name:'Actions for Delivery arrangements',exact:true});
    await opener.focus(); await opener.press('ArrowDown');
    await frame.getByRole('button',{name:'Morning delivery',exact:true}).press('Escape');
    assert.equal(await opener.evaluate(el=>el.getRootNode().activeElement===el),true);
    await open(delivery);
    await frame.getByRole('button',{name:'Clear',exact:true}).click();
    await frame.getByRole('button',{name:'Confirm',exact:true}).click();
    assert.equal(await frame.locator('#actions-city-summary').textContent(),'');
    assert.equal(await frame.locator('#actions-phone input').inputValue(),'');
    assert.equal(await frame.locator('#actions-billing-summary').textContent(),'London');
    assert.match(await frame.locator('#actions-order-reference input').inputValue(),/SO-1042/);
    assert.equal(await frame.locator('#actions-tracking-summary').textContent(),'SHIP-1042-01');
    assert.equal(await delivery.getByRole('checkbox',{name:'Reviewed',exact:true}).isChecked(),true);
    assert.equal(await address.getByRole('button',{name:'Expand card',exact:true}).count(),1);
    await frame.locator('#actions-invoiced input').check();
    await open(delivery);
    assert.equal(await frame.getByRole('button',{name:'Clear',exact:true}).isDisabled(),true);
    await frame.getByRole('button',{name:'Morning delivery',exact:true}).press('Escape');
    await frame.getByRole('button',{name:'Reload shipping cards',exact:true}).click();
    await frame.getByText('Shipping editor loaded · revision 2',{exact:true}).waitFor();
    await frame.waitForFunction(()=>document.querySelector('#actions-address')?.clearItem);
    assert.equal(await delivery.getByRole('checkbox',{name:'Reviewed',exact:true}).isChecked(),true);
    assert.equal(await frame.locator('#actions-city-summary').textContent(),'');
    await open(delivery);
    assert.equal(await frame.getByRole('button',{name:'Clear',exact:true}).count(),1);
    await page.screenshot({path:'/private/tmp/card-actions-desktop.png',fullPage:true});
    await frame.getByRole('button',{name:'Morning delivery',exact:true}).press('Escape');
    await page.setViewportSize({width:560,height:960});
    await delivery.scrollIntoViewIfNeeded();
    assert.ok(await frame.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.screenshot({path:'/private/tmp/card-actions-narrow.png',fullPage:true});
    await page.setViewportSize({width:1440,height:1050});
    await page.locator('#preview-g05').getByRole('tab',{name:'Code',exact:true}).first().click();
    const code=await page.locator('#code-g05').evaluate(el=>el.parameters.value);
    assert.match(code,/@source/); assert.match(code,/def shipping_card/); assert.match(code,/def shipping_address/);
    assert.deepEqual(errors,[]);
    console.log('g05: custom actions, nested/full Clear, cancel, gate, keyboard, state/reload, Python sources and narrow layout passed.');
} finally { await browser.close(); }
