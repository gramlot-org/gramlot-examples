/** Real-engine mobile/desktop qualification against both hosted galleries. */
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
const [playwrightEntry, ...urls] = process.argv.slice(2);
if (!playwrightEntry || !urls.length) throw new Error('Usage: verify_gallery_mobile.mjs PLAYWRIGHT_ENTRY URL...');
const {chromium, webkit} = await import(pathToFileURL(playwrightEntry));
for (const [name, engine] of [['chromium', chromium], ['webkit', webkit]]) {
    const browser = await engine.launch({headless: true});
    try { for (const url of urls) {
        const page = await browser.newPage({viewport: {width: 390, height: 844}, isMobile: true, hasTouch: true});
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.goto(url);
        const menu = page.locator('#gallery-mobile-menu');
        await menu.waitFor({state: 'visible'});
        // Source renders before the asynchronous gallery bundle finishes mounting.
        await page.locator('#gallery[data-mobile-view=example]').waitFor({state: 'visible'});
        assert.equal(await page.evaluate(() => innerWidth), 390, 'real device viewport, not 980px desktop scaling');
        assert.equal(await page.locator('#index-sidebar').isVisible(), false);
        assert.equal(await page.locator('#gallery-view-code').isDisabled(), true);
        await menu.click();
        await page.getByText('Input components', {exact: true}).first().click();
        await menu.click();
        await page.getByRole('link', {name: 'Textbox and labelbox', exact: true}).click();
        assert.equal(await page.locator('#index-sidebar').isVisible(), false);
        const frameElement = page.locator('#frame-w01');
        const field = page.frameLocator('#frame-w01').locator('#customer input');
        await field.fill('Mobile value');
        await page.evaluate(() => { window.savedFrame = document.getElementById('frame-w01'); window.savedWindow = window.savedFrame.contentWindow; });
        assert.ok((await frameElement.boundingBox()).width >= 389, 'example uses the available width');
        await page.locator('#gallery-view-code').click();
        assert.equal(await page.locator('#index-code').isVisible(), true);
        assert.equal(await frameElement.isVisible(), false);
        assert.ok((await page.locator('#index-code').boundingBox()).width >= 389);
        await page.locator('#gallery-view-inspector').click();
        const inspector = page.locator('gramlot-tools-inspector');
        const row = inspector.locator('gramlot-poc-tree[data-root=data] [data-node-path=customer]');
        await row.click();
        const value = inspector.getByLabel('Value', {exact: true});
        assert.equal(await value.inputValue(), 'Mobile value');
        await value.fill('Inspector edit'); await value.press('Enter');
        await page.locator('#gallery-view-example').click();
        assert.equal(await field.inputValue(), 'Inspector edit', 'editing the inspector updates the original Data');
        await page.locator('#gallery-view-inspector').click();
        assert.equal(await value.inputValue(), 'Inspector edit', 'selection is retained');
        await value.fill('Blur commit');
        await page.locator('#gallery-view-code').click();
        await page.locator('#gallery-view-inspector').click();
        assert.equal(await value.inputValue(), 'Blur commit', 'inspector edit survives hiding (normal blur commits)');
        await value.fill('Inspector edit'); await value.press('Enter');
        await page.screenshot({path: `/tmp/gallery-mobile-${name}-${new URL(url).port}-inspector.png`});
        await menu.click();
        assert.equal(await page.locator('#gallery-inspector-panel').getAttribute('inert'), '');
        await page.keyboard.press('Escape');
        assert.equal(await page.locator('#index-sidebar').isVisible(), false);
        await menu.click();
        await page.locator('#gallery-mobile-backdrop').click({position: {x: 380, y: 20}});
        assert.equal(await page.locator('#index-sidebar').isVisible(), false);
        await page.locator('#gallery-view-example').click();
        for (const width of [320, 390, 768, 1023]) {
            await page.setViewportSize({width, height: 844});
            await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
        }
        await page.setViewportSize({width: 1200, height: 900});
        await page.locator('#index-code-toggle').waitFor({state: 'visible'});
        assert.equal(await frameElement.isVisible(), true);
        assert.equal(await page.locator('#index-code').isVisible(), true);
        await page.locator('#gallery-inspector').click();
        assert.equal(await inspector.locator('gramlot-poc-palette').isVisible(), true);
        assert.equal(await inspector.getAttribute('docked'), null);
        await page.setViewportSize({width: 390, height: 844});
        await page.locator('#gallery-view-inspector').click();
        assert.equal(await value.inputValue(), 'Inspector edit');
        await page.locator('#gallery-view-example').click();
        assert.equal(await field.inputValue(), 'Inspector edit');
        assert.equal(await page.evaluate(() => savedFrame === document.getElementById('frame-w01') && savedWindow === savedFrame.contentWindow), true);
        await page.screenshot({path: `/tmp/gallery-mobile-${name}-${new URL(url).port}-example.png`});
        await menu.click();
        await page.getByRole('link', {name: 'Validation rules and callbacks', exact: true}).click();
        const invalid = page.frameLocator('#frame-w25').locator('#full-name input');
        await invalid.fill('A');
        await page.locator('#gallery-view-code').click();
        await page.locator('#gallery-view-inspector').click();
        await page.locator('#gallery-view-example').click();
        assert.equal(await invalid.inputValue(), 'A', 'rejected widget draft survives view changes');
        const validationFrame = page.frames().find(frame => (/\/w25(?:\/index\.html)?$/).test(new URL(frame.url()).pathname));
        assert.equal(await validationFrame.evaluate(() => gramlot.data.getItem('profile.full_name')), 'Ada Lovelace');
        assert.equal(await invalid.getAttribute('aria-invalid'), 'true');
        assert.deepEqual(errors, []);
        console.log(`PASS ${name} ${url}: 320–1023px, drawer, full-width views, same iframe/Data, inspector edit/selection, rejected field draft, desktop round trip`);
        await page.close();
    }} finally { await browser.close(); }
}
