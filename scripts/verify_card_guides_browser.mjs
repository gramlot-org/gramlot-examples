import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {fromTytx} from '@genrojs/tytx';
import {galleryRow} from './gallery-navigation.mjs';

const browser=await chromium.launch({headless:true});
try {
    const page=await browser.newPage({viewport:{width:1440,height:1050}});
    const errors=[], calls=[];
    page.on('pageerror',error=>errors.push(error.message));
    page.on('request',request=>{if(request.method()==='POST' && request.url().endsWith('/gramlot/rpc')) calls.push(fromTytx(request.postData()));});
    await page.goto(process.argv[2]);
    await page.waitForFunction(()=>window.gramlot?.state==='started');
    await (await galleryRow(page,'g06')).click();
    const frame=await (await page.locator('#frame-g06').elementHandle()).contentFrame();
    await frame.waitForFunction(()=>window.gramlot?.state==='started');
    await frame.locator('#guide-address-city input').waitFor();
    const count=()=>calls.filter(call=>/^guided_/.test(call.name)).length;
    const initial=count();
    const customer=frame.locator('#guide-customer'), delivery=frame.locator('#guide-delivery'), address=frame.locator('#guide-address');
    const customerButton=customer.getByRole('button',{name:'Guide for North Workshop Ltd',exact:true});
    await customerButton.focus(); await customerButton.press('Enter');
    assert.match(await customer.getByRole('dialog').innerText(),/country prefix/);
    await customer.getByRole('button',{name:'Close guide'}).press('Escape');
    assert.equal(await customerButton.evaluate(el=>el.getRootNode().activeElement===el),true);
    await customerButton.press('Space');
    await customer.getByRole('button',{name:'Close guide'}).click();
    await frame.locator('#guide-customer-contact input').fill('Sam Taylor');
    await frame.locator('#guide-address-city input').fill('Bath');
    const guide=delivery.getByRole('button',{name:'Guide for Delivery plan',exact:true});
    await guide.click();
    assert.match(await delivery.getByRole('dialog').innerText(),/Sam Taylor/);
    assert.match(await delivery.getByRole('dialog').innerText(),/Bath/);
    await delivery.getByRole('button',{name:'Close guide'}).click();
    await delivery.getByRole('checkbox',{name:'Reviewed',exact:true}).check();
    await delivery.getByRole('button',{name:'Collapse card',exact:true}).first().click();
    await guide.click();
    assert.equal(await delivery.getByRole('button',{name:'Expand card',exact:true}).count(),1);
    assert.match(await delivery.getByRole('dialog').innerText(),/Bath/);
    await page.screenshot({path:'/private/tmp/card-doc-folded.png',fullPage:true});
    await delivery.getByRole('button',{name:'Close guide'}).click();
    await delivery.getByRole('button',{name:'Expand card',exact:true}).click();
    await address.getByRole('button',{name:'Guide for Workshop address',exact:true}).click();
    assert.match(await address.getByRole('dialog').innerText(),/Gate B/);
    await address.getByRole('button',{name:'Close guide'}).press('Escape');
    assert.equal(count(),initial,'reading/folding guides makes no RPC');
    await frame.locator('#guide-visible input').uncheck();
    assert.equal(await guide.isVisible(),false);
    await frame.locator('#guide-visible input').check();
    await delivery.getByRole('button',{name:'Collapse card',exact:true}).first().click();
    await frame.getByRole('button',{name:'Reload guided cards',exact:true}).click();
    await frame.getByText('Guided cards loaded · revision 2',{exact:true}).waitFor();
    await frame.waitForFunction(()=>document.querySelector('#guide-address-city'));
    assert.equal(await delivery.getByRole('checkbox',{name:'Reviewed',exact:true}).isChecked(),true);
    assert.equal(await frame.locator('#guide-contact-summary').textContent(),'Sam Taylor');
    assert.equal(await frame.locator('#guide-city-summary').textContent(),'Bath');
    await guide.click();
    assert.match(await delivery.getByRole('dialog').innerText(),/Bath/);
    // A server/controller-driven refresh can remove a card while its native popup is open.
    await frame.evaluate(()=>window.gramlot.data.setItem('order.revision',3));
    await frame.getByText('Guided cards loaded · revision 3',{exact:true}).waitFor();
    await frame.waitForFunction(()=>document.querySelector('#guide-address-city'));
    assert.equal(await guide.getAttribute('aria-expanded'),'false');
    await guide.click();
    assert.match(await delivery.getByRole('dialog').innerText(),/Bath/);
    await page.screenshot({path:'/private/tmp/card-doc-desktop.png',fullPage:true});
    await page.setViewportSize({width:560,height:960});
    await delivery.scrollIntoViewIfNeeded();
    assert.ok(await frame.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    const popup=delivery.getByRole('dialog');
    assert.ok(await popup.evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0 && r.right<=innerWidth+1 && r.top>=0 && r.bottom<=innerHeight+1;}));
    await page.screenshot({path:'/private/tmp/card-doc-narrow.png',fullPage:true});
    await delivery.getByRole('button',{name:'Close guide'}).press('Escape');
    await page.setViewportSize({width:1440,height:1050});
    await page.locator('#preview-g06').getByRole('tab',{name:'Code',exact:true}).first().click();
    const code=await page.locator('#code-g06').evaluate(el=>el.parameters.value);
    for(const name of ['guided_cards','guided_delivery','guided_address']) assert.match(code,new RegExp('def '+name));
    assert.match(code,/@source/);
    assert.deepEqual(errors,[]);
    console.log('g06: useful Markdown guides, Enter/Space/Escape/focus, contextual values, folded/nested cards, empty guide, reload, no guide RPC, Code and narrow geometry passed.');
} finally {await browser.close();}
