import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const [entry,base='http://127.0.0.1:8243/']=process.argv.slice(2);
const {chromium,webkit}=await import(pathToFileURL(entry));
const catalogue=JSON.parse(await readFile(new URL('../src/gramlot_examples/catalog.json',import.meta.url)));
const demos=catalogue.families.flatMap(f=>f.examples).filter(d=>d.key!=='l08');
for(const [name,type] of Object.entries({chromium,webkit})) {
 const browser=await type.launch();
 try {
  const page=await browser.newPage({viewport:{width:1100,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(new URL('l08',base).href);
  const stack=page.locator('#stack-demo'),slider=page.locator('#stack-panel input');
  await stack.locator('iframe').first().waitFor();
  assert.equal(await stack.locator('iframe').count(),demos.length);
  assert.equal(await page.locator('#mini-l08').count(),0);
  assert.equal(await slider.getAttribute('max'),String(demos.length-1));
  await page.frameLocator('#mini-e01').getByRole('heading',{name:'Hello, Gramlot!'}).waitFor();
  await page.frameLocator('#live-e01').getByRole('heading',{name:'Hello, Gramlot!'}).waitFor();
  assert.equal(await page.locator('#live-e02').getAttribute('src'),null);
  await slider.press('ArrowRight');
  assert.equal(await page.locator('#stack-page').innerText(),'Demo: e02');
  assert.equal(await page.locator('#live-e02').getAttribute('src'),null,'center must wait for debounce');
  await slider.press('ArrowRight');
  await page.waitForFunction(()=>document.querySelector('#live-e03').getAttribute('src')==='e03');
  assert.equal(await page.locator('#live-e02').getAttribute('src'),null,'intermediate center frame must not load');
  await slider.press('End');
  assert.equal(await page.locator('#stack-page').innerText(),'Demo: '+demos.at(-1).key);
  await slider.press('Home');
  const index=demos.findIndex(d=>d.key==='b01');
  for(let i=0;i<index;i++)await slider.press('ArrowRight');
  const caption=page.frameLocator('#mini-b01').locator('#caption-field');await caption.waitFor();
  await caption.fill('Retained in a miniature');await caption.press('Tab');
  const frame=await page.locator('#mini-b01').elementHandle();
  await frame.evaluate(el=>{el.ownerDocument.retainedFrame=el;el.ownerDocument.retainedWindow=el.contentWindow;el.ownerDocument.retainedDocument=el.contentDocument;});
  await slider.press('ArrowRight');await slider.press('ArrowLeft');
  assert.equal(await caption.inputValue(),'Retained in a miniature');
  assert.ok(await frame.evaluate(el=>el===el.ownerDocument.retainedFrame&&el.contentWindow===el.ownerDocument.retainedWindow&&el.contentDocument===el.ownerDocument.retainedDocument));
  assert.equal(await page.frameLocator('#mini-b01').locator('#caption').innerText(),'Retained in a miniature');
  assert.equal(await page.locator('#stack-caption').innerText(),demos[index].title);
  const dimensions=await frame.evaluate(el=>({visual:el.getBoundingClientRect().width,logical:el.offsetWidth}));
  assert.ok(Math.abs(dimensions.visual/dimensions.logical-.5)<.01);
  const live=page.frameLocator('#live-b01').locator('#caption-field');await live.waitFor();
  await live.fill('Retained in the center');await live.press('Tab');
  const fullFrame=await page.locator('#live-b01').elementHandle();
  await fullFrame.evaluate(el=>el.ownerDocument.retainedFullDocument=el.contentDocument);
  await slider.press('ArrowRight');
  await page.waitForFunction(()=>gramlot.data.getItem('stackDemo.active')==='b02');
  await slider.press('ArrowLeft');
  await page.waitForFunction(()=>gramlot.data.getItem('stackDemo.active')==='b01');
  assert.equal(await live.inputValue(),'Retained in the center');
  assert.ok(await fullFrame.evaluate(el=>el.contentDocument===el.ownerDocument.retainedFullDocument));
  assert.equal(await caption.inputValue(),'Retained in a miniature','the two instances keep independent Data');
  await page.screenshot({path:`/tmp/stack-carousel-${name}.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.equal(await caption.inputValue(),'Retained in a miniature');
  const drawer=page.locator('#carousel-layout .separator[data-side=left] .drawer');
  const before=await page.locator('#stack-full').boundingBox();await drawer.click();
  assert.equal(await drawer.getAttribute('aria-expanded'),'false');
  const after=await page.locator('#stack-full').boundingBox();assert.ok(after.width>before.width+150);
  assert.equal(await live.inputValue(),'Retained in the center');
  await page.screenshot({path:`/tmp/stack-carousel-mobile-${name}.png`,fullPage:true});
  await drawer.click();assert.equal(await caption.inputValue(),'Retained in a miniature');
  assert.deepEqual(errors,[]);
  console.log(`${name}: ${demos.length} thumbnail/full pairs, debounce and deferred center src, independent retained Data/documents, drawer and narrow viewport passed`);
 } finally {await browser.close();}
}
